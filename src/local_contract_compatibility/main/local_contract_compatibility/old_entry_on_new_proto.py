from __future__ import annotations

import os
import pathlib
import subprocess
import sys

from local_contract_compatibility.mode_id import ModeId


def get_test_dir_rel_path(package_name: str) -> pathlib.Path:
    return pathlib.Path("src") / package_name / "test" / f"test_{package_name}" / "test_slow_integrated" / "test_old_entry_on_new_proto"


def run_old_entry_on_new_proto(
    repo_dir_abs_path: pathlib.Path,
    package_name: str,
    commit_name: str,
    pytest_args: list[str],
) -> int:
    """
    Runs the `old_entry_on_new_proto` tests: an entry script generated by `commit_name`'s
    committed `proto_kernel.py` (via its own `wrap`) against the current `proto_kernel.py`/`venv`.

    FT_78_72_23_04.backward_compatibility.md
    """

    test_dir_rel_path = get_test_dir_rel_path(package_name)
    if not (repo_dir_abs_path / test_dir_rel_path).is_dir():
        raise AssertionError(f"[{test_dir_rel_path}] does not exist")

    # `CI` is required, otherwise `test_slow_integrated` tests are skipped:
    sub_env = dict(os.environ)
    sub_env["CI"] = "true"
    exit_code = subprocess.run(
        [sys.executable, "-m", "pytest", "-p", "no:cacheprovider", str(test_dir_rel_path), "--commit_name", commit_name] + pytest_args,
        cwd=str(repo_dir_abs_path),
        env=sub_env,
    ).returncode

    if exit_code != 0:
        print(
            f"FAILED: mode [{ModeId.old_entry_on_new_proto.value}], commit name [{commit_name}]: " f"the changes break backward compatibility tests in the baseline - possible actions: " f"[A] fix changes to comply [B] update the baseline",
            file=sys.stderr,
        )
    return exit_code
