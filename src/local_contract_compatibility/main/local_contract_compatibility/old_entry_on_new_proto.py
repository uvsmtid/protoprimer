from __future__ import annotations

import os
import pathlib
import shutil
import subprocess
import sys
import tempfile
from typing import Dict, Optional

from local_contract_compatibility.mode_id import ModeId
from local_contract_compatibility.run_mode_tests import run_handoff_mode_tests


def generate_entry_script_content_via_old_wrap(
    old_proto_kernel_abs_path: pathlib.Path,
    entry_func: str,
    proto_kernel_abs_path: str,
    entry_script_abs_path: str,
    module_name: Optional[str],
    func_name: Optional[str],
    env_vars: Optional[Dict[str, str]] = None,
) -> str:
    """
    Same signature as `generate_entry_script_content`, but the text is generated by `wrap` of the old `proto_kernel.py`.

    The text refers to `proto_kernel.py` by the relative path from the entry script: `wrap` is run
    from a scratch tree where the old copy has the same relative path from the entry script.
    """

    if env_vars:
        raise NotImplementedError("`wrap` cannot set env vars into the entry script")

    proto_kernel_rel_path = os.path.relpath(proto_kernel_abs_path, os.path.dirname(entry_script_abs_path))
    levels_up = proto_kernel_rel_path.split(os.sep).count(os.pardir)

    with tempfile.TemporaryDirectory() as scratch_dir_name:
        scratch_entry_dir_abs_path = pathlib.Path(scratch_dir_name).joinpath(*["d"] * levels_up)
        scratch_proto_kernel_abs_path = pathlib.Path(os.path.normpath(scratch_entry_dir_abs_path / proto_kernel_rel_path))
        scratch_proto_kernel_abs_path.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(old_proto_kernel_abs_path, scratch_proto_kernel_abs_path)
        scratch_entry_script_abs_path = scratch_entry_dir_abs_path / os.path.basename(entry_script_abs_path)
        scratch_entry_script_abs_path.parent.mkdir(parents=True, exist_ok=True)

        wrap_args = [sys.executable, str(scratch_proto_kernel_abs_path), "wrap", entry_func, "-s", str(scratch_entry_script_abs_path)]
        if module_name:
            wrap_args += ["-m", f"{module_name}:{func_name}"]
        subprocess.run(wrap_args, cwd=scratch_dir_name, check=True)

        return scratch_entry_script_abs_path.read_text()


def run_old_entry_on_new_proto(
    repo_dir_abs_path: pathlib.Path,
    package_name: str,
    commit_name: str,
    pytest_args: list[str],
) -> int:
    """
    Runs the `old_entry_on_new_proto` tests: an entry script generated by `commit_name`'s
    committed `proto_kernel.py` (via its own `wrap`) against the current `proto_kernel.py`/`venv`.

    FT_78_72_23_04.backward_compatibility.md
    """

    return run_handoff_mode_tests(
        ModeId.old_entry_on_new_proto,
        repo_dir_abs_path,
        package_name,
        commit_name,
        pytest_args,
    )
