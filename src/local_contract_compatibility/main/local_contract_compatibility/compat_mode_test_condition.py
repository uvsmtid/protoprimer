    if "generate_entry_script_content" in test_module_globals:
        monkeypatch.setitem(
            test_module_globals,
            "generate_entry_script_content",
            functools.partial(generate_entry_script_content_via_old_wrap, old_proto_kernel_abs_path),
        )
