import pathlib
import subprocess

from local_contract_compatibility.old_proto_on_new_venv import extract_old_proto_kernel
from local_test.fat_mocked_helper import run_primer_main
from local_test.integrated_helper import create_max_leaps_shape, create_plain_proto_kernel
from local_test.name_assertion import (
    assert_test_func_name_embeds_str,
    assert_test_module_name_embeds_str,
)
from protoprimer.primer_kernel import (
    EntryFunc,
    ExecOperation,
    SyntaxArg,
    TopDir,
)


def test_relationship():
    assert_test_module_name_embeds_str(EntryFunc.func_boot_env.value)


def test_old_entry_script_boot_env(
    tmp_path: pathlib.Path,
    commit_name: str,
    repo_dir_abs_path: pathlib.Path,
):
    """
    An entry script generated by `commit_name`'s committed `proto_kernel.py` (via its own `wrap`)
    must still boot the current `protoprimer` (new `proto_kernel.py`, new `venv`):
    see `old_entry_on_new_proto` in "Modes (ids)".

    FT_78_72_23_04.backward_compatibility.md
    """

    assert_test_func_name_embeds_str(EntryFunc.func_boot_env.value)

    # given:

    (
        proto_kernel_abs_path,
        ref_root_abs_path,
        project_dir_abs_path,
    ) = create_max_leaps_shape(tmp_path)

    entry_script_abs_path = ref_root_abs_path / EntryFunc.func_boot_env.value

    # Temporarily put the old `proto_kernel.py` in place, just to let its own `wrap` generate
    # the entry script (with its own, possibly older, boilerplate/template):
    extract_old_proto_kernel(
        repo_dir_abs_path,
        commit_name,
        proto_kernel_abs_path,
    )

    run_primer_main(
        [
            str(proto_kernel_abs_path),
            ExecOperation.op_wrap.value,
            EntryFunc.func_boot_env.value,
            SyntaxArg.arg_entry_script_path,
            str(entry_script_abs_path),
        ]
    )

    # Put the current `proto_kernel.py` back: the entry script must boot the *new* code,
    # not the old one used only to generate it:
    create_plain_proto_kernel(proto_kernel_abs_path.parent)

    # when:

    subprocess.run(
        [str(entry_script_abs_path)],
        check=True,
    )

    # then:

    assert (ref_root_abs_path / TopDir.dir_venv.value).exists()
