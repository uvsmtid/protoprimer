# Matches tag prefixes like `FT_00_00_00_00` or `UC_00_00_00_00` at start of title.
_TAGGED_TITLE_RE = re.compile(r"^[A-Z]+_\d+_\d+_\d+_\d+\.")


def _strip_tag_prefix(text: str) -> str:
    # Remove leading tag like `FT_00_00_00_00` or `UC_00_00_00_00` from a title string.
    return _TAGGED_TITLE_RE.sub("", text)


def _on_doctree_resolved(
    app,
    doctree,
    docname,
):
    # Strip tag prefix from the first title node (page <h1>).
    # Fires after `toctree` has already captured `env.titles`,
    # so `reference.html` listings keep the full prefixed title
    # while the individual page shows only the suffix
    # (e.g. `some_name` instead of `FT_00_00_00_00.some_name`).
    for node in doctree.traverse(nodes.title):
        raw = node.astext()
        stripped = _strip_tag_prefix(raw)
        if stripped != raw:
            node.clear()
            node += nodes.Text(stripped)
        break


def _on_html_page_context(
    app,
    pagename,
    templatename,
    context,
    doctree,
):
    # Strip tag prefix from `context["title"]`
    # so the browser tab title matches the stripped <h1> set by `_on_doctree_resolved`.
    if "title" in context:
        context["title"] = _strip_tag_prefix(context["title"])


# Matches the `<meta>` tag (`.. meta::` directive) with the page description:
_META_DESCRIPTION_RE = re.compile(r'<meta content="([^"]*)" name="description" />')


def _get_meta_description(context) -> str:
    description_match = _META_DESCRIPTION_RE.search(context.get("metatags", ""))
    return html.unescape(description_match.group(1)) if description_match else ""


def _on_html_page_context_for_og(
    app,
    pagename,
    templatename,
    context,
    doctree,
):
    # `sphinxext-opengraph` takes `og:title` from the <h1> and `og:description` from the first text of a page.
    # Use `seo_title` and `:description:` instead (the same as for `<title>` and `<meta name="description">`).
    # Page fields starting with `og:` override the extension values.
    page_meta = dict(context.get("meta") or {})
    if page_meta.get("seo_title"):
        page_meta.setdefault("og:title", str(page_meta["seo_title"]))
    description = _get_meta_description(context)
    if description:
        page_meta.setdefault("og:description", description)
    context["meta"] = page_meta


def _strip_html(text: str) -> str:
    return html.unescape(re.sub(r"<[^>]+>", "", text))


def _on_html_page_context_for_json_ld(
    app,
    pagename,
    templatename,
    context,
    doctree,
):
    # Structured data (Schema.org `JSON-LD`) for the pages with `seo_title` (the landing page and the docs):
    # values come from the page itself (`seo_title`, `:description:`, the page position in `toctree`).
    seo_title = (context.get("meta") or {}).get("seo_title")
    if not seo_title:
        return
    # Redirect pages (`noindex`) get no structured data:
    if "noindex" in context.get("metatags", ""):
        return
    site_url = app.config.html_baseurl
    page_url = urljoin(site_url, app.builder.get_target_uri(pagename))
    description = _get_meta_description(context)

    if pagename == "intro":
        graph = [
            {
                "@type": "SoftwareSourceCode",
                "name": app.config.project,
                "description": description,
                "url": page_url,
                "codeRepository": github_url,
                "programmingLanguage": "Python",
                "license": "https://spdx.org/licenses/MIT.html",
            },
        ]
    else:
        breadcrumb_items = [
            (app.config.project, urljoin(site_url, app.builder.get_target_uri("intro"))),
            *[(_strip_html(parent["title"]), urljoin(page_url, parent["link"])) for parent in context.get("parents", [])],
            (_strip_html(context["title"]), page_url),
        ]
        graph = [
            {
                "@type": "TechArticle",
                "headline": str(seo_title),
                "description": description,
                "url": page_url,
                "inLanguage": "en",
                "isPartOf": {
                    "@type": "WebSite",
                    "name": app.config.project,
                    "url": site_url,
                },
            },
            {
                "@type": "BreadcrumbList",
                "itemListElement": [
                    {
                        "@type": "ListItem",
                        "position": position,
                        "name": item_name,
                        "item": item_url,
                    }
                    for position, (item_name, item_url) in enumerate(breadcrumb_items, start=1)
                ],
            },
        ]

    # Escape `</` to keep the content from closing the `<script>` element:
    context["json_ld"] = json.dumps(
        {
            "@context": "https://schema.org",
            "@graph": graph,
        },
        indent=2,
    ).replace("</", "<\\/")


def setup(app):
    app.connect("doctree-resolved", _on_doctree_resolved)
    app.connect("html-page-context", _on_html_page_context)
    # Must run before the `sphinxext-opengraph` handler (default priority is 500):
    app.connect("html-page-context", _on_html_page_context_for_og, priority=400)
    app.connect("html-page-context", _on_html_page_context_for_json_ld)
